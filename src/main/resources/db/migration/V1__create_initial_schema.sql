
-- CARP-4 : Schéma initial de Carpooling

-- 1. Conducteurs
CREATE TABLE conducteurs (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             nom VARCHAR(100) NOT NULL,
                             prenom VARCHAR(100) NOT NULL,
                             email VARCHAR(255) NOT NULL,
                             telephone VARCHAR(30) NOT NULL,
                             numero_permis VARCHAR(50) NOT NULL,

                             CONSTRAINT uq_conducteurs_email UNIQUE (email),
                             CONSTRAINT uq_conducteurs_permis UNIQUE (numero_permis)
);

-- 2. Passagers
CREATE TABLE passagers (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nom VARCHAR(100) NOT NULL,
                           prenom VARCHAR(100) NOT NULL,
                           email VARCHAR(255) NOT NULL,
                           telephone VARCHAR(30) NOT NULL
);

-- 3. Véhicules
CREATE TABLE vehicules (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           marque VARCHAR(100) NOT NULL,
                           modele VARCHAR(100) NOT NULL,
                           immatriculation VARCHAR(30) NOT NULL,
                           couleur VARCHAR(50) NOT NULL,
                           capacite INTEGER NOT NULL,
                           conducteur_id BIGINT NOT NULL,

                           CONSTRAINT uq_vehicules_immatriculation
                               UNIQUE (immatriculation),

                           CONSTRAINT ck_vehicules_capacite
                               CHECK (capacite BETWEEN 1 AND 8),

                           CONSTRAINT fk_vehicules_conducteur
                               FOREIGN KEY (conducteur_id)
                                   REFERENCES conducteurs(id)
);

-- 4. Trajets
CREATE TABLE trajets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         conducteur_id BIGINT NOT NULL,
                         vehicule_id BIGINT NOT NULL,
                         date_depart TIMESTAMP NOT NULL,
                         places_proposees INTEGER NOT NULL,
                         statut VARCHAR(20) NOT NULL,

                         CONSTRAINT fk_trajets_conducteur
                             FOREIGN KEY (conducteur_id)
                                 REFERENCES conducteurs(id),

                         CONSTRAINT fk_trajets_vehicule
                             FOREIGN KEY (vehicule_id)
                                 REFERENCES vehicules(id),

                         CONSTRAINT ck_trajets_places
                             CHECK (places_proposees >= 1),

                         CONSTRAINT ck_trajets_statut
                             CHECK (statut IN (
                                               'PUBLIE', 'COMPLET', 'TERMINE', 'ANNULE'
                                 ))
);

-- 5. Points d'arrêt
CREATE TABLE points_arret (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              trajet_id BIGINT NOT NULL,
                              ville VARCHAR(100) NOT NULL,
                              ordre INTEGER NOT NULL,
                              heure_passage TIMESTAMP NOT NULL,
                              prix_depuis_depart NUMERIC(10,2) NOT NULL,

                              CONSTRAINT fk_points_arret_trajet
                                  FOREIGN KEY (trajet_id)
                                      REFERENCES trajets(id),

                              CONSTRAINT uq_points_arret_ordre
                                  UNIQUE (trajet_id, ordre),

                              CONSTRAINT ck_points_arret_ordre
                                  CHECK (ordre >= 0),

                              CONSTRAINT ck_points_arret_prix
                                  CHECK (prix_depuis_depart >= 0),

                              CONSTRAINT ck_points_arret_ville
                                  CHECK (btrim(ville) <> '')
);

CREATE UNIQUE INDEX uq_points_arret_trajet_ville
    ON points_arret (trajet_id, lower(btrim(ville)));

-- 6. Réservations
CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              passager_id BIGINT NOT NULL,
                              trajet_id BIGINT NOT NULL,
                              point_montee_id BIGINT NOT NULL,
                              point_descente_id BIGINT NOT NULL,
                              nombre_places INTEGER NOT NULL,
                              montant_total NUMERIC(10,2) NOT NULL,
                              date_reservation TIMESTAMP NOT NULL,
                              statut VARCHAR(20) NOT NULL,

                              CONSTRAINT fk_reservations_passager
                                  FOREIGN KEY (passager_id)
                                      REFERENCES passagers(id),

                              CONSTRAINT fk_reservations_trajet
                                  FOREIGN KEY (trajet_id)
                                      REFERENCES trajets(id),

                              CONSTRAINT fk_reservations_montee
                                  FOREIGN KEY (point_montee_id)
                                      REFERENCES points_arret(id),

                              CONSTRAINT fk_reservations_descente
                                  FOREIGN KEY (point_descente_id)
                                      REFERENCES points_arret(id),

                              CONSTRAINT ck_reservations_places
                                  CHECK (nombre_places >= 1),

                              CONSTRAINT ck_reservations_montant
                                  CHECK (montant_total > 0),

                              CONSTRAINT ck_reservations_statut
                                  CHECK (statut IN ('CONFIRMEE', 'ANNULEE'))
);

-- Une seule réservation confirmée
-- par passager et par trajet
CREATE UNIQUE INDEX uq_reservation_confirmee
    ON reservations (passager_id, trajet_id)
    WHERE statut = 'CONFIRMEE';

CREATE INDEX idx_reservations_trajet_statut
    ON reservations (trajet_id, statut);
